//! Headless output formatting: text (stream) / rich JSON (buffered), truncation of large
//! results, and redaction of secrets in error messages (REQ-H13, REQ-H14, REQ-H15c).
//!
//! Two orthogonal formatters over the same [`RunOutcome`]:
//! - [`write_text`] writes only the `response` to `out` (plus a clamp warning to `err_out` if applicable) — for `--output-format text` (default).
//! - [`write_json`] serializes **a single buffered JSON object**, with `schema_version` as the **first physical field** (REQ-H14), truncating each large `result`/`content` to the effective cap ([`TOOL_RESULT_CAP`](super::limits::TOOL_RESULT_CAP) by default) with a marker.
//!
//! [`sanitize_error_message`] is the security boundary for any error text that may have been
//! generated by an external layer (HTTP provider, SQLite, IO): **allowlist-first** — it
//! classifies the error class and returns a fixed template message, without echoing the raw
//! tail of the message — with a **safety net** based on key-like patterns as a last resort for
//! text that does not match any known template.
//!
//! These formatters are `pub`: the MS2 runner lives in the binary crate and can only reach
//! `pub` API from the lib.

