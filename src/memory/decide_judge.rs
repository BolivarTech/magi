use std::sync::Arc;

use async_trait::async_trait;
use magi_rs::decision::internal::{
    contradiction_request, log_fallback, Consumer, FallbackCause, NOUL_YES_THRESHOLD,
};
use magi_rs::decision::{Answer, AttemptOutcome, Cause, DecisionClient, Trace};

use crate::agent::decide_classifier::last_attempt_detail;

use crate::memory::error::MemoryError;
