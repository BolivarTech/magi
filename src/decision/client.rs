//! One System One attempt over HTTP and the client that walks the chain (REQ-D00, REQ-D03,
//! REQ-D04, REQ-D07, REQ-D10).

use crate::decision::config::{KeepAlive, ModelSpec};
use crate::decision::endpoint::{not_found_hint, systemone_url};
use crate::decision::error::{
    Attempt, AttemptOutcome, Cause, Decision, DecisionError, Trace, Usage,
};
use crate::decision::protocol::{
    lowest_confidence, parse_response, salvage_usage, DecisionRequest, ParsedResponse,
};
use crate::redact::{redact_foreign_error, redact_foreign_text, redact_url};
use std::time::{Duration, Instant};

/// Tracing target of every decision log entry.
pub const DECISION_LOG_TARGET: &str = "magi_rs::decision";
/// Most bytes of an error body that are read to pick a `cause` token or to relay a rejection.
pub const NOT_FOUND_BODY_READ_CAP: usize = 64 * 1024;
/// A System One answer for a few questions is a few KiB; anything past this is not read and is an
/// invalid response.
pub const RESPONSE_BODY_CAP: usize = 1024 * 1024;
/// Ollama 0.35.0, captured 2026-10-01: `{"error":"model \"<m>\" not found, try pulling it first"}`.
pub const MODEL_NOT_FOUND_MARKERS: &[&str] = &["not found, try pulling it first"];
/// OpenRouter, E4: "0 endpoints out of 1 requested are available matching your guardrail
/// restrictions and data policy...".
pub const ACCOUNT_POLICY_MARKERS: &[&str] = &["guardrail restrictions and data policy"];

/// Asks System One models for typed decisions.
#[cfg_attr(test, mockall::automock)]
#[async_trait::async_trait]
pub trait DecisionClient: Send + Sync {
    /// One System One request through the fallback chain (REQ-D00).
    ///
    /// # Arguments
    /// * `request` - the validated request.
    ///
    /// # Returns
    /// The decision with the chain walked to get it.
    ///
    /// # Errors
    /// A [`DecisionError`] carrying the trace of every attempt.
    async fn decide(&self, request: &DecisionRequest) -> Result<Decision, DecisionError>;
}

/// Everything the client needs, already resolved.
#[derive(Clone)]
pub struct DecisionSettings {
    /// Resolved `base_url` (placeholders substituted).
    pub base_url: String,
    /// Key for the endpoint, if any.
    pub api_key: Option<zeroize::Zeroizing<String>>,
    /// Models in order.
    pub chain: Vec<ModelSpec>,
    /// Per-attempt timeout.
    pub timeout: Duration,
    /// Sent verbatim when declared.
    pub keep_alive: Option<KeepAlive>,
}

impl std::fmt::Debug for DecisionSettings {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DecisionSettings")
            .field("base_url", &crate::redact::redact_url(&self.base_url))
            .field("api_key", &self.api_key.as_ref().map(|_| "<set>"))
            .field("chain", &self.chain)
            .field("timeout", &self.timeout)
            .field("keep_alive", &self.keep_alive)
            .finish()
    }
}

/// Why one attempt produced no decision.
struct Failure {
    cause: Cause,
    /// Text generated by Magi; never provider text.
    detail: Option<String>,
    /// HTTP status, when the provider answered.
    status: Option<u16>,
    /// Redacted, capped provider body; only a rejection relays it.
    provider_message: String,
    /// Consumption the provider reported in a body that was otherwise unusable.
    usage: Usage,
}

impl Failure {
    fn new(cause: Cause, detail: Option<String>) -> Self {
        Self {
            cause,
            detail,
            status: None,
            provider_message: String::new(),
            usage: Usage::default(),
        }
    }

    fn http(cause: Cause, detail: Option<String>, status: u16) -> Self {
        Self {
            status: Some(status),
            ..Self::new(cause, detail)
        }
    }
}

/// Appended to a 400/422 detail when `keep_alive` was sent (REQ-D01).
pub(crate) const KEEP_ALIVE_HINT: &str =
    "; keep_alive was sent and providers other than Ollama may reject it";

/// HTTP implementation of [`DecisionClient`].
///
/// The key is resolved once, when the client is built: a `vault set DECISION_API_KEY` from
/// another process is not seen until the process restarts.
///
/// # Examples
///
/// ```no_run
/// use magi_rs::decision::{DecisionSettings, ModelSpec, SystemOneClient};
/// use std::time::Duration;
///
/// let client = SystemOneClient::new(DecisionSettings {
///     base_url: "http://localhost:11434".into(),
///     api_key: None,
///     chain: vec![ModelSpec { model: "nimble".into(), min_confidence: None }],
///     timeout: Duration::from_secs(120),
///     keep_alive: None,
/// })?;
/// # Ok::<(), magi_rs::decision::DecisionError>(())
/// ```
pub struct SystemOneClient {
    http: reqwest::Client,
    url: String,
    url_display: String,
    settings: DecisionSettings,
}

impl SystemOneClient {
    /// Builds the client: redirects off (a key must never follow one to another host) and no
    /// total timeout (each request carries its own).
    ///
    /// # Arguments
    /// * `settings` - the resolved settings.
    ///
    /// # Errors
    /// `ClientUnavailable` when the HTTP client cannot be built.
    pub fn new(settings: DecisionSettings) -> Result<Self, DecisionError> {
        let http = reqwest::Client::builder()
            .redirect(reqwest::redirect::Policy::none())
            .build()
            .map_err(|e| DecisionError::ClientUnavailable {
                reason: redact_foreign_error(&e).to_string(),
            })?;
        let url = systemone_url(&settings.base_url);
        let url_display = redact_url(&url);
        Ok(Self {
            http,
            url,
            url_display,
            settings,
        })
    }

    /// The `base_url`, redacted.
    ///
    /// # Returns
    /// The endpoint as shown to users: credentials replaced, never a key.
    pub fn endpoint_display(&self) -> String {
        redact_url(&self.settings.base_url)
    }

    /// One HTTP attempt with `model`.
    async fn attempt(
        &self,
        model: &str,
        request: &DecisionRequest,
        body: &serde_json::Value,
    ) -> Result<ParsedResponse, Failure> {
        let timeout = request.timeout().unwrap_or(self.settings.timeout);
        let mut builder = self.http.post(&self.url).timeout(timeout).json(body);
        if let Some(key) = &self.settings.api_key {
            builder = builder.bearer_auth(key.as_str());
        }
        let mut response = builder.send().await.map_err(transport_failure)?;
        let status = response.status().as_u16();
        match status {
            200..=299 => {
                let (bytes, over_cap) = read_capped(&mut response, RESPONSE_BODY_CAP)
                    .await
                    .map_err(transport_failure)?;
                if over_cap {
                    return Err(Failure::new(
                        Cause::InvalidResponse,
                        Some("invalid response: the body is larger than the read cap".into()),
                    ));
                }
                parse_response(&bytes, request.questions()).map_err(|reason| {
                    let mut detail = format!("invalid response: {reason}");
                    // A body that is not JSON at all is typically a web page answered by a
                    // base_url without the provider's API prefix: diagnose it like a 404.
                    if serde_json::from_slice::<serde_json::Value>(&bytes).is_err() {
                        detail.push_str("; ");
                        detail.push_str(&not_found_hint(&self.url_display));
                    }
                    Failure {
                        usage: salvage_usage(&bytes),
                        ..Failure::new(Cause::InvalidResponse, Some(detail))
                    }
                })
            }
            300..=399 => Err(Failure::http(
                Cause::Redirected,
                Some(redirect_detail(&response)),
                status,
            )),
            _ => Err(self.error_status(model, status, &mut response).await),
        }
    }

    /// Classifies a 4xx/5xx answer; the body picks the token and, for a rejection, is relayed.
    async fn error_status(
        &self,
        model: &str,
        status: u16,
        response: &mut reqwest::Response,
    ) -> Failure {
        let (bytes, _) = read_capped(response, NOT_FOUND_BODY_READ_CAP)
            .await
            .unwrap_or_default();
        let body = String::from_utf8_lossy(&bytes);
        let failure = match status {
            401 | 403 => Failure::http(Cause::Unauthorized, None, status),
            400 | 413 | 422 => {
                let mut detail =
                    format!("provider rejected the request as invalid (HTTP {status})");
                if self.settings.keep_alive.is_some() && status != 413 {
                    detail.push_str(KEEP_ALIVE_HINT);
                }
                Failure {
                    provider_message: redact_foreign_text(&body).to_string(),
                    ..Failure::http(Cause::Rejected, Some(detail), status)
                }
            }
            404 => {
                let (cause, detail) = if contains_any(&body, MODEL_NOT_FOUND_MARKERS) {
                    (
                        Cause::ModelNotFound,
                        format!("model '{model}' is not available on this endpoint"),
                    )
                } else if contains_any(&body, ACCOUNT_POLICY_MARKERS) {
                    (
                        Cause::AccountPolicy,
                        format!(
                            "the provider excluded model '{model}' by account policy \
                             (data or privacy settings)"
                        ),
                    )
                } else {
                    (Cause::NotFound, not_found_hint(&self.url_display))
                };
                Failure::http(cause, Some(detail), status)
            }
            429 => Failure::http(Cause::RateLimited, None, status),
            500..=599 => Failure::http(Cause::Http5xx, Some(format!("HTTP {status}")), status),
            _ => Failure::http(
                Cause::InvalidResponse,
                Some(format!("unexpected HTTP status {status}")),
                status,
            ),
        };
        // A spent attempt still counts when its error body reports consumption.
        Failure {
            usage: salvage_usage(&bytes),
            ..failure
        }
    }
}

/// Whether `body` contains any of the `markers`.
fn contains_any(body: &str, markers: &[&str]) -> bool {
    markers.iter().any(|m| body.contains(m))
}

/// Maps a `reqwest` error to a timeout or a transport failure.
fn transport_failure(error: reqwest::Error) -> Failure {
    if error.is_timeout() {
        Failure::new(Cause::Timeout, None)
    } else {
        Failure::new(Cause::Transport, None)
    }
}

/// Names the host a 3xx points to, redacted; the header is provider text, so only its host is used.
fn redirect_detail(response: &reqwest::Response) -> String {
    let host = response
        .headers()
        .get(reqwest::header::LOCATION)
        .and_then(|v| v.to_str().ok())
        .and_then(|v| reqwest::Url::parse(v).ok())
        .and_then(|u| u.host_str().map(str::to_owned))
        .map_or_else(
            || "another location".to_owned(),
            |h| redact_foreign_text(&h).to_string(),
        );
    format!("the endpoint redirected to {host}; redirects are not followed")
}

/// Reads at most `cap` bytes of the body; the flag says whether more was available.
///
/// Complexity: O(min(body, cap)).
async fn read_capped(
    response: &mut reqwest::Response,
    cap: usize,
) -> Result<(Vec<u8>, bool), reqwest::Error> {
    let mut bytes = Vec::new();
    while let Some(chunk) = response.chunk().await? {
        let room = cap - bytes.len();
        if chunk.len() > room {
            bytes.extend_from_slice(chunk.get(..room).unwrap_or_default());
            return Ok((bytes, true));
        }
        bytes.extend_from_slice(&chunk);
    }
    Ok((bytes, false))
}

/// Milliseconds since `since`, saturating.
fn elapsed_ms(since: Instant) -> u64 {
    u64::try_from(since.elapsed().as_millis()).unwrap_or(u64::MAX)
}

impl SystemOneClient {
    /// The models to try: the explicit one alone (with the threshold of the declared model of that
    /// name, if any) or the whole configured chain.
    fn plan(&self, request: &DecisionRequest) -> Vec<ModelSpec> {
        match request.model() {
            Some(model) => vec![ModelSpec {
                model: model.to_owned(),
                min_confidence: self
                    .settings
                    .chain
                    .iter()
                    .find(|spec| spec.model == model)
                    .and_then(|spec| spec.min_confidence),
            }],
            None => self.settings.chain.clone(),
        }
    }

    /// One run-log event for an attempt; never the state, the key or provider text (REQ-D17).
    fn log_attempt(&self, attempt: &Attempt, latency_ms: u64) {
        let (outcome, cause) = match &attempt.outcome {
            AttemptOutcome::Answered => ("answered", None),
            AttemptOutcome::Failed { cause, .. } => ("failed", Some(cause.as_str())),
            AttemptOutcome::LowConfidence { .. } => ("low_confidence", None),
        };
        let (confidence, min_confidence) = match &attempt.outcome {
            AttemptOutcome::LowConfidence {
                confidence,
                min_confidence,
                ..
            } => (Some(*confidence), Some(*min_confidence)),
            _ => (None, None),
        };
        let endpoint = self.endpoint_display();
        tracing::event!(
            target: DECISION_LOG_TARGET,
            tracing::Level::INFO,
            model = attempt.model.as_str(),
            outcome = outcome,
            cause = cause,
            confidence = confidence,
            min_confidence = min_confidence,
            endpoint = endpoint.as_str(),
            latency_ms = latency_ms,
            input_tokens = attempt.usage.input_tokens,
            output_tokens = attempt.usage.output_tokens,
            "decision attempt"
        );
    }

    /// The closing run-log event of one call.
    fn log_close(&self, answered_by: Option<&str>, trace: &Trace, started: Instant) {
        tracing::event!(
            target: DECISION_LOG_TARGET,
            tracing::Level::INFO,
            model = answered_by.unwrap_or("none"),
            attempts = trace.attempts.len(),
            input_tokens = trace.usage.input_tokens,
            output_tokens = trace.usage.output_tokens,
            total_ms = elapsed_ms(started),
            endpoint = self.endpoint_display().as_str(),
            "decision finished"
        );
    }

    /// Records one attempt in the trace, the usage sum and the run log.
    fn record(&self, trace: &mut Trace, attempt: Attempt, latency_ms: u64) {
        trace.usage.add(&attempt.usage);
        self.log_attempt(&attempt, latency_ms);
        trace.attempts.push(attempt);
    }
}

#[async_trait::async_trait]
impl DecisionClient for SystemOneClient {
    /// Walks the chain in order (or tries only the explicit model). An answer whose lowest
    /// confidence is under that model's `min_confidence` is recorded and the chain rotates; a
    /// rejected answer is never returned (REQ-D20).
    ///
    /// Complexity: O(m) attempts for m models.
    async fn decide(&self, request: &DecisionRequest) -> Result<Decision, DecisionError> {
        let started = Instant::now();
        let mut trace = Trace::default();
        for spec in self.plan(request) {
            let attempt_started = Instant::now();
            // A serialization failure ends the call as an explicit error: no empty body is sent.
            let body = request.wire_body(&spec.model, self.settings.keep_alive.as_ref())?;
            let result = self.attempt(&spec.model, request, &body).await;
            let latency_ms = elapsed_ms(attempt_started);
            match result {
                Ok(parsed) => {
                    let lowest = lowest_confidence(&parsed.answers);
                    let below = spec.min_confidence.filter(|min| lowest < *min);
                    let outcome = match below {
                        Some(min_confidence) => AttemptOutcome::LowConfidence {
                            confidence: lowest,
                            min_confidence,
                            answers: parsed.answers.clone(),
                        },
                        None => AttemptOutcome::Answered,
                    };
                    let attempt = Attempt {
                        model: spec.model.clone(),
                        outcome,
                        usage: parsed.usage,
                    };
                    self.record(&mut trace, attempt, latency_ms);
                    if below.is_none() {
                        self.log_close(Some(&spec.model), &trace, started);
                        return Ok(Decision {
                            model: spec.model,
                            answers: parsed.answers,
                            trace,
                        });
                    }
                }
                Err(failure) => {
                    let attempt = Attempt {
                        model: spec.model.clone(),
                        outcome: AttemptOutcome::Failed {
                            cause: failure.cause,
                            detail: failure.detail,
                        },
                        usage: failure.usage,
                    };
                    self.record(&mut trace, attempt, latency_ms);
                    if !failure.cause.rotates() {
                        // The only causes that do not rotate end the call with their own error.
                        self.log_close(None, &trace, started);
                        let status = failure.status.unwrap_or_default();
                        return Err(if failure.cause == Cause::Unauthorized {
                            DecisionError::Unauthorized { status, trace }
                        } else {
                            DecisionError::Rejected {
                                status,
                                provider_message: failure.provider_message,
                                trace,
                            }
                        });
                    }
                }
            }
        }
        self.log_close(None, &trace, started);
        Err(match request.model() {
            Some(model) => DecisionError::ModelUnavailable {
                model: model.to_owned(),
                trace,
            },
            None => DecisionError::ChainExhausted { trace },
        })
    }
}

