    /// S12: an internal fallback shows nothing on any screen. Every event emitted while the
    /// fallbacks run is the INFO entry of the fallback target; nothing else is logged.
    #[test]
    fn a_fallback_emits_only_info_events_of_the_fallback_target() {
        struct Everything(Arc<Mutex<Vec<(String, tracing::Level)>>>);
        impl<S: tracing::Subscriber> tracing_subscriber::Layer<S> for Everything {
            fn on_event(
                &self,
                e: &tracing::Event<'_>,
                _: tracing_subscriber::layer::Context<'_, S>,
            ) {
                if let Ok(mut v) = self.0.lock() {
                    v.push((e.metadata().target().to_string(), *e.metadata().level()));
                }
            }
        }
        let seen = Arc::new(Mutex::new(Vec::new()));
        let _g = tracing::subscriber::set_default(
            tracing_subscriber::registry().with(Everything(Arc::clone(&seen))),
        );
        let rt = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .expect("rt");
        rt.block_on(async {
            classifier(Some(Scripted::new(dead())), Fallback::new(None))
                .classify("x")
                .await;
            classifier(None, Fallback::new(None)).classify("x").await;
            classifier(Some(Scripted::new(chose("design"))), Fallback::new(None))
                .with_max_state_bytes(LIMIT)
                .classify(&"x".repeat(LIMIT))
                .await;
        });
        let seen = seen.lock().expect("seen").clone();
        assert_eq!(seen.len(), 3, "{seen:?}");
        for (target, level) in seen {
            assert_eq!(target, magi_rs::decision::internal::FALLBACK_LOG_TARGET);
            assert_eq!(level, tracing::Level::INFO);
        }
    }

