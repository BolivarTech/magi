/// Field of the decision state that carries the consult content.
const STATE_REQUEST_FIELD: &str = "request";

/// Mode classifier that asks `decide` first and falls back to the principal LLM in the same
/// inference (REQ-D12).
///
/// Content whose serialized state exceeds the configured `[decision].max_state_bytes` goes
/// straight to the fallback: a decision over truncated text looks as sure as one over the whole
/// text (D-PM-1).
/// Every fallback leaves one run-log entry and nothing on any screen.
pub struct DecideModeClassifier {
    /// Decision client, or `None` when it could not be built.
    client: Option<Arc<dyn DecisionClient>>,
    /// LLM classifier used when `decide` cannot answer.
    fallback: Arc<dyn ModeClassifier>,
    /// Redacted endpoint shown in the run log.
    endpoint: String,
    /// Why the client could not be built, as Magi worded it (already redacted).
    unavailable_reason: Option<String>,
    /// Largest serialized state, in bytes, sent to `decide` (D-PM-1).
    max_state_bytes: usize,
}

impl DecideModeClassifier {
    /// Builds the classifier.
    ///
    /// # Arguments
    /// * `client` - The decision client, if one could be built.
    /// * `fallback` - The LLM classifier to use when `decide` fails.
    /// * `endpoint` - The redacted decision endpoint, for the run log.
    ///
    /// # Returns
    /// The classifier.
    pub fn new(
        client: Option<Arc<dyn DecisionClient>>,
        fallback: Arc<dyn ModeClassifier>,
        endpoint: String,
    ) -> Self {
        Self {
            client,
            fallback,
            endpoint,
            unavailable_reason: None,
            max_state_bytes: crate::defaults::DEFAULT_DECISION_MAX_STATE_BYTES,
        }
    }

    /// Records why the client could not be built, so the `client_unavailable` entry carries it.
    ///
    /// # Arguments
    /// * `reason` - Redacted text generated by Magi, if the client could not be built.
    ///
    /// # Returns
    /// The classifier, with the reason attached.
    pub fn with_unavailable_reason(mut self, reason: Option<String>) -> Self {
        self.unavailable_reason = reason;
        self
    }

    /// Sets the largest serialized state, in bytes, sent to `decide`.
    ///
    /// # Arguments
    /// * `max_state_bytes` - The configured `[decision].max_state_bytes`.
    ///
    /// # Returns
    /// The classifier, with the limit applied.
    pub fn with_max_state_bytes(mut self, max_state_bytes: usize) -> Self {
        self.max_state_bytes = max_state_bytes;
        self
    }

    /// Logs the fallback and asks the LLM classifier.
    ///
    /// # Arguments
    /// * `content` - The content to classify.
    /// * `cause` - Why `decide` did not answer.
    /// * `detail` - Detail generated by Magi, if any.
    ///
    /// # Returns
    /// The LLM classifier's answer, `None` included.
    async fn fall_back(
        &self,
        content: &str,
        cause: FallbackCause,
        detail: Option<&str>,
    ) -> Option<Mode> {
        log_fallback(Consumer::Mode, cause, &self.endpoint, detail);
        self.fallback.classify(content).await
    }
}

/// The detail Magi generated for the last attempt of a failed decision.
///
/// # Arguments
/// * `error` - The error the client returned.
///
/// # Returns
/// The detail, or `None` when the error has no failed attempt with one.
pub(crate) fn last_attempt_detail(error: &DecisionError) -> Option<&str> {
    match error.trace()?.attempts.last().map(|a| &a.outcome) {
        Some(AttemptOutcome::Failed { detail, .. }) => detail.as_deref(),
        _ => None,
    }
}

/// The mode chosen by the first `choice` answer of a decision.
///
/// # Arguments
/// * `answers` - The answers of the decision.
///
/// # Returns
/// The mode, or `None` when no answer is a choice of a known label.
fn chosen_mode<'a>(answers: impl IntoIterator<Item = &'a Answer>) -> Option<Mode> {
    answers.into_iter().find_map(|answer| match answer {
        Answer::Choice { choice, .. } => mode_from_label(choice),
        _ => None,
    })
}

#[async_trait]
impl ModeClassifier for DecideModeClassifier {
    async fn classify(&self, content: &str) -> Option<Mode> {
        let Some(client) = self.client.as_ref() else {
            return self
                .fall_back(
                    content,
                    FallbackCause::ClientUnavailable,
                    self.unavailable_reason.as_deref(),
                )
                .await;
        };
        let state = json!({ STATE_REQUEST_FIELD: content });
        let state_bytes = serde_json::to_vec(&state).map_or(usize::MAX, |v| v.len());
        if state_bytes > self.max_state_bytes {
            return self.fall_back(content, FallbackCause::TooLarge, None).await;
        }
        let request = match DecisionRequest::new(state, mode_questions()) {
            Ok(request) => request,
            Err(e) => {
                return self
                    .fall_back(content, FallbackCause::from_error(&e), None)
                    .await;
            }
        };
        match client.decide(&request).await {
            Ok(decision) => match chosen_mode(decision.answers.values()) {
                Some(mode) => Some(mode),
                None => {
                    self.fall_back(
                        content,
                        FallbackCause::Attempt(Cause::InvalidResponse),
                        None,
                    )
                    .await
                }
            },
            Err(e) => {
                self.fall_back(
                    content,
                    FallbackCause::from_error(&e),
                    last_attempt_detail(&e),
                )
                .await
            }
        }
    }
}

/// Captures every event of the fallback target.
#[cfg(test)]
pub(crate) fn fallback_lines<F: std::future::Future<Output = ()>>(f: F) -> Vec<String> {
    use std::sync::{Arc, Mutex};
    use tracing_subscriber::layer::SubscriberExt;
    struct Capture(Arc<Mutex<Vec<String>>>);
    impl<S: tracing::Subscriber> tracing_subscriber::Layer<S> for Capture {
        fn on_event(&self, e: &tracing::Event<'_>, _: tracing_subscriber::layer::Context<'_, S>) {
            if e.metadata().target() == magi_rs::decision::internal::FALLBACK_LOG_TARGET {
                if let Ok(mut v) = self.0.lock() {
                    v.push(magi_rs::logging::render::render_event(e));
                }
            }
        }
    }
    let lines = Arc::new(Mutex::new(Vec::new()));
    let _g = tracing::subscriber::set_default(
        tracing_subscriber::registry().with(Capture(Arc::clone(&lines))),
    );
    let rt = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("rt");
    rt.block_on(f);
    let v = lines.lock().expect("lines").clone();
    v
}

